export type AvailabilityStatus = 'available' | 'partially-available' | 'unavailable';

/** Sundays are always unavailable, regardless of calendar entries or updater output. */
export const isAvailabilityWorkingDay = (date: string) =>
  new Date(`${date}T12:00:00Z`).getUTCDay() !== 0;

// Inclusive date ranges added only at Blaze's explicit request. Keep reasons private.
export const availabilityProtectedRanges: Array<{ start: string; end: string }> = [];

/** The annual break and explicitly requested protections override calendar entries. */
export const isAvailabilityProtectedDate = (date: string) => {
  const monthDay = date.slice(5);
  return monthDay >= '12-20' || monthDay <= '01-03'
    || availabilityProtectedRanges.some(range => date >= range.start && date <= range.end);
};

